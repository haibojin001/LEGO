"""Build ``benchmark/tasks.jsonl`` and the standard splits from frozen task dirs.

    python benchmark/build_index.py [--bench benchmark] [--metadata benchmark/metadata.jsonl]

For every ``tasks/<name>/`` with a frozen grading key this writes one index
line (pinned commit, package prefix, test path, module count, ceiling/floor
sizes, difficulty band of Eq. 6, and the domain/track/stars from
``metadata.jsonl``). The checked-in ``lego_repo_522.txt`` is an immutable
membership list from the historical A/B task records. It includes 11 tasks
that exceeded the generation cap and therefore contributed zero; it must not
be regenerated by filtering the current task directories. Other splits:

  lego_repo_available.txt  frozen tasks within the current module cap
  over_cap.txt        tasks above the current module cap (still in the index)
  dev_25.txt          5 tasks per band, for quick end-to-end checks
  stars_*.txt         star-count strata (contamination analysis)
"""

import argparse
import json
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from lego.benchmark_meta import HELD_REPOS  # noqa: E402
from lego.harness.task import band_of  # noqa: E402

MIN_SPAN = int(os.environ.get("LEGO_MIN_SPAN", 5))
MAX_MODULES = int(os.environ.get("LEGO_MAX_MODULES", 300))


def ids(p):
    return [l.strip() for l in open(p) if l.strip()] if os.path.exists(p) else []


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bench", default="benchmark")
    ap.add_argument("--metadata", default=None)
    a = ap.parse_args()
    meta_p = a.metadata or os.path.join(a.bench, "metadata.jsonl")
    meta = {}
    if os.path.exists(meta_p):
        for l in open(meta_p):
            if l.strip():
                r = json.loads(l)
                meta[r["name"]] = r
    rows, over = [], []
    tdir = os.path.join(a.bench, "tasks")
    for name in sorted(os.listdir(tdir)):
        d = os.path.join(tdir, name)
        tj = os.path.join(d, "task.json")
        if name in HELD_REPOS or not os.path.exists(tj):
            continue
        task = json.load(open(tj))
        C = ids(os.path.join(d, "expected", "ceiling.txt"))
        F = set(ids(os.path.join(d, "expected", "floor.txt"))) & set(C)
        if not C or len(C) - len(F) < MIN_SPAN:
            continue
        n_mod = int(task.get("n_modules") or sum(
            1 for _r, _d, fs in os.walk(os.path.join(d, "original"))
            for f in fs if f.endswith(".py")))
        m = meta.get(name, {})
        row = {"name": name, "clone": task["clone"], "commit": task["commit"],
               "package": task["package"], "src_prefix": task.get("src_prefix", "."),
               "project_dir": task.get("project_dir", "."),
               "tests": task.get("test_path", "tests"),
               "domain": m.get("domain", ""), "track": m.get("track", ""),
               "stars": m.get("stars", 0), "n_modules": n_mod,
               "ceiling": len(C), "floor": len(F), "band": band_of(n_mod, len(C))}
        rows.append(row)
        if n_mod > MAX_MODULES:
            over.append(row)
    with open(os.path.join(a.bench, "tasks.jsonl"), "w") as fh:
        for r in rows:
            fh.write(json.dumps(r) + "\n")
    sp = os.path.join(a.bench, "splits")
    os.makedirs(sp, exist_ok=True)
    available = [r for r in rows if r["n_modules"] <= MAX_MODULES]
    paper_path = os.path.join(sp, "lego_repo_522.txt")
    split_text = "".join(r["name"] + "\n" for r in available)
    count_path = os.path.join(sp, f"lego_repo_{len(available)}.txt")
    if count_path != paper_path or not os.path.exists(paper_path):
        open(count_path, "w").write(split_text)
    open(os.path.join(sp, "lego_repo_available.txt"), "w").write(split_text)
    paper, missing = [], []
    if os.path.isfile(paper_path):
        paper = [line.strip() for line in open(paper_path) if line.strip()]
        if len(paper) != 522 or len(set(paper)) != 522:
            raise SystemExit(f"{paper_path}: expected 522 unique task names")
        by_name = {r["name"]: r for r in rows}
        missing = sorted(set(paper) - by_name.keys())
        if missing:
            print(f"[index] paper split incomplete locally: {len(missing)} "
                  f"tasks missing frozen keys (example: {missing[:5]})")
        else:
            bands = [sum(by_name[name]["band"] == b for name in paper)
                     for b in range(1, 6)]
            if bands != [117, 111, 116, 96, 82]:
                raise SystemExit(f"paper split bands changed: {bands}")
            print(f"[index] paper split: 522 tasks, bands {bands}")
    open(os.path.join(sp, "over_cap.txt"), "w").write(
        "".join(r["name"] + "\n" for r in over))
    analysis_rows = ([{r["name"]: r for r in rows}[n] for n in paper]
                     if paper and not missing
                     else available)
    for lab, lo, hi in (("stars_ge10k", 10000, 10 ** 9),
                        ("stars_3k_10k", 3000, 10000), ("stars_1k_3k", 0, 3000)):
        open(os.path.join(sp, lab + ".txt"), "w").write(
            "".join(r["name"] + "\n" for r in analysis_rows
                    if lo <= r["stars"] < hi))
    rng = random.Random("dev")
    dev = []
    for b in range(1, 6):
        pool = sorted(r["name"] for r in available if r["band"] == b)
        dev += rng.sample(pool, min(5, len(pool)))
    open(os.path.join(sp, "dev_25.txt"), "w").write("".join(n + "\n" for n in dev))
    by = {}
    for r in available:
        by[r["band"]] = by.get(r["band"], 0) + 1
    print(f"[index] tasks.jsonl: {len(rows)} frozen, {len(available)} within "
          f"cap, {len(over)} over cap; available bands "
          f"{dict(sorted(by.items()))}; missing metadata "
          f"{sum(1 for r in rows if not r['domain'])}")


if __name__ == "__main__":
    main()
